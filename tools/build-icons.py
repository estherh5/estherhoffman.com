#!/usr/bin/env python3
"""Subset the icon fonts to the glyphs index.html actually uses.

The page used to load all of Font Awesome 6.5.2 and Devicon 2.16.0 from CDNs
(~1.5MB, and Devicon's CSS lists its 1.2MB TTF before the woff, so browsers
fetched the TTF) to draw ~55 decorative 12px glyphs. This script reads every
`fa-*` / `devicon-*` class in index.html, looks up each one's codepoint in the
upstream CSS, subsets the upstream fonts to those codepoints as woff2 in
fonts/, and writes icons.css with only the rules the page needs.

Re-run after adding or changing an icon class in index.html, and commit
icons.css and fonts/ with the edit. It fails loudly on an unknown class.

Run: python3 tools/build-icons.py   (needs fontTools + brotli: pyftsubset)
"""
import io
import re
import sys
import urllib.request
from pathlib import Path

from fontTools import subset
from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parent.parent
FA = "https://cdnjs.cloudflare.com/ajax/libs/font-awesome/6.5.2"
DEVICON = "https://cdn.jsdelivr.net/gh/devicons/devicon@v2.16.0"

FONTS = {
    # family key: (upstream font URL, output file, CSS family name, weight)
    "solid": (f"{FA}/webfonts/fa-solid-900.woff2", "fa-solid.woff2", "EH FA Solid", 900),
    "brands": (f"{FA}/webfonts/fa-brands-400.woff2", "fa-brands.woff2", "EH FA Brands", 400),
    "devicon": (f"{DEVICON}/fonts/devicon.woff", "devicon.woff2", "EH Devicon", 400),
}


def fetch(url: str) -> bytes:
    req = urllib.request.Request(url, headers={"User-Agent": "icon-subset-build"})
    with urllib.request.urlopen(req, timeout=60) as r:
        return r.read()


def codepoints(css: str, prefix: str) -> dict[str, int]:
    """Map `<prefix>name` -> codepoint from `.name:before{content:"\\f41b"}`
    rules (selector lists included) and FA 6's `--fa:"\\f41b"` form."""
    out: dict[str, int] = {}
    for selectors, body in re.findall(r"([^{}]+)\{([^{}]*)\}", css):
        # FA writes an escape ("\\f41b"); Devicon writes the literal character.
        m = re.search(r'(?:content|--fa)\s*:\s*"(?:\\([0-9a-fA-F]+)|([^"\\]))"', body)
        if not m:
            continue
        cp = int(m.group(1), 16) if m.group(1) else ord(m.group(2))
        for name in re.findall(r"\.(" + re.escape(prefix) + r"[a-z0-9-]+)", selectors):
            out.setdefault(name, cp)
    return out


def main() -> int:
    html = (ROOT / "index.html").read_text()
    classes = set(re.findall(r"\b((?:fa|devicon)-[a-z0-9-]+)", html))
    used_fa = sorted(c for c in classes if c.startswith("fa-") and c not in ("fa-solid", "fa-brands"))
    used_dev = sorted(c for c in classes if c.startswith("devicon-"))

    fa_map = codepoints(fetch(f"{FA}/css/all.min.css").decode(), "fa-")
    dev_map = codepoints(fetch(f"{DEVICON}/devicon.min.css").decode(), "devicon-")

    # Each fa-* glyph is drawn by whichever style class sits beside it.
    style_of: dict[str, str] = {}
    for style, name in re.findall(r'class="[^"]*\bfa-(solid|brands)\s+(fa-[a-z0-9-]+)', html):
        style_of[name] = style

    missing = [c for c in used_fa if c not in fa_map or c not in style_of]
    missing += [c for c in used_dev if c not in dev_map]
    if missing:
        print("unknown icon class(es): " + ", ".join(missing), file=sys.stderr)
        return 1

    wanted = {"solid": {}, "brands": {}, "devicon": {}}
    for c in used_fa:
        wanted[style_of[c]][c] = fa_map[c]
    for c in used_dev:
        wanted["devicon"][c] = dev_map[c]

    (ROOT / "fonts").mkdir(exist_ok=True)
    css = [
        "/* Generated by tools/build-icons.py from Font Awesome 6.5.2 (Free, CC BY 4.0",
        "   icons / SIL OFL fonts) and Devicon 2.16.0 (MIT). Do not edit by hand. */",
    ]
    for key, (url, out, family, weight) in FONTS.items():
        font = TTFont(io.BytesIO(fetch(url)))
        opts = subset.Options()
        opts.flavor = "woff2"
        opts.layout_features = []
        opts.name_IDs = [0, 1, 2]  # keep the license/copyright notice
        sub = subset.Subsetter(opts)
        sub.populate(unicodes=sorted(set(wanted[key].values())))
        sub.subset(font)
        buf = io.BytesIO()
        font.flavor = "woff2"
        font.save(buf)
        (ROOT / "fonts" / out).write_bytes(buf.getvalue())
        print(f"fonts/{out}: {len(wanted[key])} glyphs, {len(buf.getvalue())} bytes")
        css.append(
            f'@font-face{{font-family:"{family}";font-style:normal;font-weight:{weight};'
            f'font-display:block;src:url(fonts/{out}) format("woff2")}}'
        )

    css += [
        ".fa-solid,.fa-brands,[class^=devicon-],[class*=\" devicon-\"]{display:inline-block;"
        "font-style:normal;font-variant:normal;line-height:1;text-rendering:auto;"
        "-webkit-font-smoothing:antialiased;-moz-osx-font-smoothing:grayscale}",
        '.fa-solid{font-family:"EH FA Solid";font-weight:900}',
        '.fa-brands{font-family:"EH FA Brands";font-weight:400}',
        '[class^=devicon-],[class*=" devicon-"]{font-family:"EH Devicon";font-weight:400}',
    ]
    for key in ("solid", "brands", "devicon"):
        for name, cp in sorted(wanted[key].items()):
            css.append(f'.{name}::before{{content:"\\{cp:x}"}}')
    (ROOT / "icons.css").write_text("\n".join(css) + "\n")
    print(f"icons.css: {sum(len(v) for v in wanted.values())} icons")
    return 0


if __name__ == "__main__":
    sys.exit(main())
